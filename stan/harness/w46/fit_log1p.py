    out.append(f"// degree {D}: |fit err| on S = {mp.nstr(e, 4)}")
    out.append(f"inline constexpr double LOG1P_S{D}[{D + 1}] = {{")
    out.append(",\n".join(f"    {mp.nstr(ck, 21)}" for ck in c))
    out.append("};")
